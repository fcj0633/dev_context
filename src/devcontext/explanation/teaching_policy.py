ABSTRACT_TERMS = ("状态推进", "收敛", "裁决", "原子范围", "原子性", "临界区", "副作用",
                  "幂等", "补偿", "最终一致", "事务边界")


def strategy_prompt() -> str:
    return "\n".join(f"{kind}: {strategy}" for kind, strategy in QUESTION_STRATEGIES.items())


def language_prompt() -> str:
    glossary = "\n".join(f"{term}：{meaning}" for term, meaning in TEACHING_GLOSSARY.items())
    return """给一个有 Java 基础、但首次阅读本项目的人讲解。目标是建立正确、简单、能复述的心智模型。
1. 按“现象 → 为什么需要解决 → 解决办法 → 术语名称 → 代码证明”的顺序解释。
2. 每节只完成 reader_takeaway；key_points 是必须讲到的事实，不是罗列清单。
3. 正文首次引入术语时先说普通中文含义再命名；每节只引入 new_terms 中最多两个术语，已解释术语可复用。
4. 先说代码在业务上做什么，再给类名、方法名、状态名；不要连续堆代码标识符。
5. 并发、事务、幂等、补偿等难理解时用一个短场景；人数、票数和异常条件明确标为“假设”。不是每节都要举例。
6. 句子短，一个句子说明一个主要关系；不要用多层从句讲完整条调用链。
7. 引用放在对应解释段末尾并靠近支持的事实，不要每句话重复引用；每个引用独立写成 [E数字]。
8. 会改变结论的证据缺口立即说明；非关键缺口集中到计划末尾已有章节，不擅自增加章节。
9. 不扩展计划之外的知识，不为凑字数重复铺垫；不要求每节机械地写成四段。
10. 第一节简短直接回答，不在第一节讲完所有细节；最后用计划中的收束章节串起主线。
以下词表只帮助表达，不是项目事实，也不能抹去真实条件、时序和边界：
""" + glossary
